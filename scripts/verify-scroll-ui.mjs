// 复用项目约定的受管浏览器；不启动日常 Chrome，不使用个人 profile。
// 启动 npm run preview -- --port 3101 后运行 node scripts/verify-scroll-ui.mjs。
// 可用 UI_QA_URL / UI_QA_OUTPUT / BROWSER_QA_RUNTIME 覆盖本机路径。
import { writeFile, mkdir } from 'node:fs/promises';
import { homedir, tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const runtime = process.env.BROWSER_QA_RUNTIME || resolve(homedir(), '.codex/tools/browser-qa/runtime.mjs');
const { withManagedBrowser } = await import(pathToFileURL(runtime).href);
const checks = [], errors = [];
const output = process.env.UI_QA_OUTPUT || resolve(tmpdir(), 'cduyzh-scroll-qa');
const origin = process.env.UI_QA_URL || 'http://127.0.0.1:3101/';
await mkdir(output, { recursive: true });
const check = (name, pass, evidence) => { checks.push({name, pass, evidence}); console.log(JSON.stringify({name,pass,evidence})); };
await withManagedBrowser(async ({ context, signal }) => {
  await context.route('https://cloud.umami.is/**', route => route.abort());
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({width:1440,height:900});
  await page.goto(origin, {waitUntil:'networkidle'});
  const scroll = async y => { signal.throwIfAborted(); await page.evaluate(y => window.scrollTo({top:y,behavior:'instant'}), y); await page.waitForTimeout(120); };
  const scene = async (selector,p) => {
    const y = await page.locator(selector).evaluate((el,p) => el.getBoundingClientRect().top + scrollY + (el.offsetHeight-innerHeight)*p, p);
    await scroll(y);
  };
  const sample = () => page.evaluate(() => {
    const rect=s=>{const r=document.querySelector(s).getBoundingClientRect();return {top:r.top,bottom:r.bottom,left:r.left,right:r.right,width:r.width,height:r.height}};
    return {scrollY,stage:rect('.hero-stage'),titleOpacity:getComputedStyle(document.querySelector('.hero-intro')).opacity,detailOpacity:getComputedStyle(document.querySelector('.hero-reveal')).opacity,transform:getComputedStyle(document.querySelector('.hero-product')).transform,product:rect('.hero-product'),phone:rect('.product-companion'),overflow:document.documentElement.scrollWidth>innerWidth};
  });
  await scroll(0);
  const start = await sample();
  await page.screenshot({path:`${output}/desktop-start.png`});
  await scene('#hero',.5); const middle=await sample();
  await page.screenshot({path:`${output}/desktop-middle.png`});
  await scene('#hero',.9); const end=await sample();
  check('desktop pinned and scrubbed',Math.abs(middle.stage.top)<1 && start.transform!==middle.transform && +middle.titleOpacity<.01 && +middle.detailOpacity>.99,{start,middle,end});
  await scene('#hero',0); const reverse=await sample();
  check('reverse scroll restores initial state',reverse.transform===start.transform && +reverse.titleOpacity>.99,reverse);
  await scene('#about',0);
  const portraitBefore = await page.locator('.about-portrait img').evaluate(el=>getComputedStyle(el).transform);
  await scene('#about',.5);
  await page.screenshot({path:`${output}/desktop-about.png`});
  check('about portrait scrubs',portraitBefore !== await page.locator('.about-portrait img').evaluate(el=>getComputedStyle(el).transform));
  check('about stays pinned',await page.locator('.about-stage').evaluate(el=>Math.abs(el.getBoundingClientRect().top)<1));
  await page.locator('#nav-link-projects').click();
  await page.waitForTimeout(1100);
  check('nav projects anchor',await page.locator('#projects').evaluate(el=>el.getBoundingClientRect().top>=60 && el.getBoundingClientRect().top<200));
  await page.screenshot({path:`${output}/desktop-projects.png`});
  check('public projects',await page.locator('#projects-list article').count()===9);
  await page.getByRole('button',{name:'已上线',exact:true}).click();
  check('live filter',await page.locator('#projects-list article').count()===3);
  await page.getByRole('button',{name:'探索中',exact:true}).click();
  check('exploring filter',await page.locator('#projects-list article').count()===6);
  await page.getByRole('button',{name:'全部作品',exact:true}).click();
  await page.getByRole('button',{name:'扫码体验',exact:true}).click();
  check('QR dialog opens',await page.locator('dialog[open]').count()===1);
  await page.keyboard.press('Escape');
  await page.waitForTimeout(100);
  check('QR Escape restores trigger',await page.locator('dialog[open]').count()===0 && await page.getByRole('button',{name:'扫码体验',exact:true}).evaluate(el=>el===document.activeElement));
  await page.locator('#nav-link-contact').click();
  await page.waitForTimeout(1100);
  await page.screenshot({path:`${output}/desktop-contact.png`});
  await context.grantPermissions(['clipboard-read','clipboard-write']);
  await page.getByRole('button',{name:'复制微信：cduyzh',exact:true}).click();
  check('WeChat copy value',await page.evaluate(()=>navigator.clipboard.readText())==='cduyzh');
  await page.evaluate(()=>{Object.defineProperty(navigator.clipboard,'writeText',{configurable:true,value:async()=>{throw new Error('blocked')}});document.execCommand=()=>false;});
  await page.getByRole('button',{name:'复制邮箱地址 cduyzh@gmail.com',exact:true}).click();
  check('copy failure feedback',await page.locator('.contact-notice-error').innerText().then(s=>s.includes('复制失败') && s.includes('cduyzh@gmail.com')));
  await page.getByRole('button',{name:'关闭提示'}).click();
  await page.setViewportSize({width:390,height:844});
  await scene('#hero',0);
  await page.screenshot({path:`${output}/mobile-start.png`});
  await scene('#hero',.55);
  check('mobile pin and no horizontal overflow',await page.locator('.hero-stage').evaluate(el=>Math.abs(el.getBoundingClientRect().top)<1) && !await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
  await page.screenshot({path:`${output}/mobile-middle.png`});
  await page.getByRole('button',{name:'打开导航菜单'}).click();
  check('mobile menu opens with focus',await page.locator('#nav-mobile-toggle').getAttribute('aria-expanded')==='true' && await page.locator('#mobile-navigation a').first().evaluate(el=>el===document.activeElement));
  await page.keyboard.press('Escape');
  check('mobile menu Escape restores focus',await page.locator('#nav-mobile-toggle').getAttribute('aria-expanded')==='false' && await page.locator('#nav-mobile-toggle').evaluate(el=>el===document.activeElement));
  await page.getByRole('button',{name:'打开导航菜单'}).click();
  await page.locator('#mobile-navigation').getByRole('link',{name:'作品',exact:true}).click();
  await page.waitForTimeout(1100);
  check('mobile navigation closes and scrolls',await page.locator('#nav-mobile-toggle').getAttribute('aria-expanded')==='false' && await page.locator('#projects').evaluate(el=>el.getBoundingClientRect().top>=50 && el.getBoundingClientRect().top<200));
  await page.screenshot({path:`${output}/mobile-projects.png`});
  await page.setViewportSize({width:320,height:640});
  await scene('#hero',0);
  check('320px no overflow',!await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
  await page.screenshot({path:`${output}/small-start.png`});
  await page.setViewportSize({width:768,height:640});
  await scene('#about',.5);
  await page.screenshot({path:`${output}/short-about.png`});
  const aboutBounds=await page.evaluate(()=>{const a=document.querySelector('.about-content').getBoundingClientRect(),f=document.querySelector('.about-footnote').getBoundingClientRect();return {contentTop:a.top,contentBottom:a.bottom,footnoteTop:f.top,height:innerHeight}});
  check('short desktop about does not clip',aboutBounds.contentTop>=64 && aboutBounds.contentBottom<aboutBounds.footnoteTop,aboutBounds);
  await page.setViewportSize({width:1440,height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  await scroll(0);
  check('live reduced motion disables pins',await page.locator('.scene-static').count()===2 && await page.locator('.hero-stage').evaluate(el=>getComputedStyle(el).position==='relative') && await page.locator('.hero-product').evaluate(el=>getComputedStyle(el).transform==='none'));
  check('live reduced mode restores visible content',await page.locator('.hero-intro').evaluate(el=>+getComputedStyle(el).opacity===1) && await page.locator('.hero-reveal').evaluate(el=>+getComputedStyle(el).opacity===1) && await page.locator('.hero-actions').evaluate(el=>!el.inert));
  await page.screenshot({path:`${output}/reduced-motion.png`});
  await page.reload({waitUntil:'networkidle'});
  await scroll(0);
  check('initial reduced mode shows title and actions',await page.locator('.hero-intro').evaluate(el=>+getComputedStyle(el).opacity===1) && await page.locator('.hero-actions').evaluate(el=>!el.inert) && await page.locator('.hero-stage').evaluate(el=>getComputedStyle(el).position==='relative'));

  await page.emulateMedia({reducedMotion:'no-preference'});
  await scene('#hero',.5);
  check('live motion restore',await page.locator('.hero-stage').evaluate(el=>getComputedStyle(el).position==='sticky') && await page.locator('.hero-intro').evaluate(el=>+getComputedStyle(el).opacity<.01));
  check('faded intro actions leave keyboard order',await page.locator('.hero-actions').evaluate(el=>el.inert));
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await scroll(0);
  check('mobile reduced mode is visible without pin or overflow',await page.locator('.hero-intro').evaluate(el=>+getComputedStyle(el).opacity===1) && await page.locator('.hero-stage').evaluate(el=>getComputedStyle(el).position==='relative') && !await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.setViewportSize({width:844,height:390});
  await scroll(0);
  check('landscape uses natural flow',await page.locator('.scene-static').count()===2 && !await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
  check('no page errors',errors.length===0,errors);
},{timeoutMs:85000});
await writeFile(`${output}/results-final.json`,JSON.stringify(checks,null,2));
if(checks.some(c=>!c.pass))process.exitCode=1;
